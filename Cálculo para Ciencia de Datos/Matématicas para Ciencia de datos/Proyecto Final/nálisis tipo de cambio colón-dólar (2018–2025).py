"""#2. Limpieza del dataset
   Realiza la limpieza completa del DataFrame:
      - Normaliza nombres de columnas
      - Elimina filas completamente vacías o duplicadas
      - Convierte la columna Fecha al tipo datetime
      - Convierte los tipos de cambio a valores numéricos
      - Elimina filas con valores nulos en columnas clave

    Parámetros:
        df (DataFrame): DataFrame crudo

    Retorna:
        DataFrame limpio
"""

#Limpieza de los Datos

def limpiar_datos(df):

    df = df.copy()

    # --- 2.1 Limpiar nombres de columnas ---
    # Quitar espacios, pasar a minúsculas, reemplazar caracteres especiales
    df.columns = (
        df.columns
        .str.strip()
        .str.lower()
        .str.replace('á', 'a').str.replace('é', 'e')
        .str.replace('í', 'i').str.replace('ó', 'o')
        .str.replace('ú', 'u')
        .str.replace(' ', '_')
        .str.replace('.', '_')
    )

    print("\n Columnas después de limpiar nombres:")
    print(list(df.columns))

    # --- 2.2 Renombrar columnas a nombres estándar ---
    # Buscar columnas que contengan palabras clave
    mapa_columnas = {}
    for col in df.columns:
        if 'fecha' in col or 'date' in col:
            mapa_columnas[col] = 'fecha'
        elif 'compra' in col or 'buy' in col or 'bid' in col:
            mapa_columnas[col] = 'compra'
        elif 'venta' in col or 'sell' in col or 'ask' in col:
            mapa_columnas[col] = 'venta'

    df = df.rename(columns=mapa_columnas)

    # Verificar que existen las columnas necesarias
    columnas_requeridas = ['fecha', 'compra', 'venta']
    for col in columnas_requeridas:
        if col not in df.columns:
            raise ValueError(f" No se encontró la columna '{col}'. "
                             f"Columnas disponibles: {list(df.columns)}")

    # Seleccionar solo las columnas necesarias
    df = df[columnas_requeridas].copy()

    # --- 2.3 Eliminar filas completamente vacías o duplicadas ---
    filas_antes = len(df)
    df = df.dropna(how='all')         # eliminar filas donde TODO es nulo
    df = df.drop_duplicates()          # eliminar duplicados exactos
    print(f"\n  Filas eliminadas (vacías/duplicadas): {filas_antes - len(df)}")

    # --- 2.4 Convertir columna 'fecha' a datetime ---
    # Intentar múltiples formatos comunes en archivos del BCCR
    formatos_fecha = ['%d/%m/%Y', '%Y-%m-%d', '%d-%m-%Y', '%m/%d/%Y', '%d/%m/%y']
    convertida = False

    for fmt in formatos_fecha:
        try:
            df['fecha'] = pd.to_datetime(df['fecha'], format=fmt)
            print(f" Fechas convertidas con formato: '{fmt}'")
            convertida = True
            break
        except Exception:
            continue

    if not convertida:
        # Último recurso: dejar que pandas lo infiera automáticamente
        df['fecha'] = pd.to_datetime(df['fecha'], infer_datetime_format=True, errors='coerce')
        print("  Fechas convertidas con inferencia automática")

    # --- 2.5 Convertir tipos de cambio a numéricos ---
    for col in ['compra', 'venta']:
        # Eliminar símbolos comunes: ₡, $, espacios, puntos de miles
        df[col] = (
            df[col].astype(str)
            .str.replace('₡', '', regex=False)
            .str.replace('$', '', regex=False)
            .str.replace(' ', '', regex=False)
            .str.replace(',', '.', regex=False)  # coma decimal → punto
        )
        df[col] = pd.to_numeric(df[col], errors='coerce')

    # --- 2.6 Filtrar el período 2018-2025 ---
    df = df[(df['fecha'].dt.year >= 2018) & (df['fecha'].dt.year <= 2025)]

    # --- 2.7 Eliminar filas con nulos en columnas clave ---
    filas_antes = len(df)
    df = df.dropna(subset=['fecha', 'compra', 'venta'])
    print(f"  Filas eliminadas (valores inválidos): {filas_antes - len(df)}")

    # --- 2.8 Ordenar por fecha ---
    df = df.sort_values('fecha').reset_index(drop=True)

    return df


