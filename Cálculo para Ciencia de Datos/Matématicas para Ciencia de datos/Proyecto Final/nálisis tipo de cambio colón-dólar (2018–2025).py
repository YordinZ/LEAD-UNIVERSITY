#Selección automática de parámetros con auto_arima
"""
ARIMA(p, d, q) tiene tres parámetros:
p = orden autorregresivo (cuántos rezagos del pasado usar)
d = grado de diferenciación (ya lo determinamos arriba)
q = orden de la media móvil (cuántos errores pasados incluir)

auto_arima prueba múltiples combinaciones y elige la que minimiza el AIC
(Akaike Information Criterion): entre menor AIC, mejor el modelo.
"""


