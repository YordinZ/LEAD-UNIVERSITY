# --- 1.3 Función de carga robusta ---
def cargar_datos(ruta):
    """
    Carga el CSV del BCCR de forma robusta, manejando:
      - Diferentes encodings (utf-8, latin-1, cp1252)
      - Separadores alternativos (; o ,)
      - Filas de encabezado adicionales al inicio
      - Nombres de columnas con espacios o caracteres especiales

    Parámetros:
        ruta (str): Ruta completa al archivo CSV

    Retorna:
        DataFrame de pandas con los datos crudos
    """
    encodings = ['utf-8', 'latin-1', 'cp1252', 'iso-8859-1']
    separadores = [',', ';', '\t']

    for encoding in encodings:
        for sep in separadores:
            try:
                # Intentar leer saltando hasta 5 filas de encabezado
                for skip in range(6):
                    try:
                        df = pd.read_csv(
                            ruta,
                            encoding=encoding,
                            sep=sep,
                            skiprows=skip,
                            thousands=',',      # manejar números con coma de miles
                            on_bad_lines='skip'
                        )
                        # Verificar que el DataFrame tiene al menos 3 columnas y filas
                        if df.shape[1] >= 3 and df.shape[0] > 10:
                            print(f" Archivo cargado con encoding='{encoding}', "
                                  f"sep='{sep}', filas_omitidas={skip}")
                            return df
                    except Exception:
                        continue
            except Exception:
                continue

    raise ValueError("No se pudo cargar el archivo. Verifica la ruta y el formato.")


