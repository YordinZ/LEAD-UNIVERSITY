# Prueba ADF, verificación de estacionariedad
"""
 Una serie es ESTACIONARIA si su media y varianza no cambian en el tiempo.
 ARIMA requiere que la serie sea estacionaria (o que la hagamos estacionaria).
 La prueba ADF (Augmented Dickey-Fuller) verifica esto estadísticamente:
  - H0 (hipótesis nula):  la serie NO es estacionaria (tiene raíz unitaria)
  - Si p-value < 0.05 → rechazamos H0 → la serie SÍ es estacionaria

"""

print("\n" + "=" * 60)
print("SECCIÓN C: PRUEBA DE ESTACIONARIEDAD (ADF)")
print("=" * 60)

def prueba_adf(serie, nombre="Serie"):
    """
    Aplica la prueba Augmented Dickey-Fuller a una serie.

    Parámetros:
        serie  (Series): serie de tiempo a evaluar
        nombre (str):    nombre descriptivo para mostrar en el resultado

    Retorna:
        es_estacionaria (bool): True si la serie es estacionaria
    """
    resultado = adfuller(serie.dropna(), autolag='AIC')
    estadistico = resultado[0]
    p_valor      = resultado[1]
    valores_crit = resultado[4]

    print(f"\n   Prueba ADF – {nombre}")
    print(f"  {'─'*45}")
    print(f"  Estadístico ADF:   {estadistico:.4f}")
    print(f"  p-value:           {p_valor:.4f}")
    print(f"  Valor crítico 1%:  {valores_crit['1%']:.4f}")
    print(f"  Valor crítico 5%:  {valores_crit['5%']:.4f}")
    print(f"  Valor crítico 10%: {valores_crit['10%']:.4f}")

    es_estacionaria = p_valor < 0.05
    if es_estacionaria:
        print(f"\n   La serie ES estacionaria (p-value = {p_valor:.4f} < 0.05)")
        print("     No se necesita diferenciación.")
    else:
        print(f"\n   La serie NO es estacionaria (p-value = {p_valor:.4f} ≥ 0.05)")
        print("     Se aplicará diferenciación (d=1).")

    return es_estacionaria


# Probar la serie original
es_estacionaria = prueba_adf(ts['promedio'], nombre="Serie Original")

